// Complete-phrase translations for the signed-in workspace, used by the in-app translator
// (dom-translator.ts). Each English phrase maps to [Gujarati, Hindi]. Whole phrases are matched,
// so screens read naturally instead of word by word. Business data (supplier and product names,
// amounts, invoice numbers) is never listed here and is never translated.
import type { Locale } from "@/lib/i18n/catalog";

export function phraseColumn(locale: Locale): 0 | 1 | null {
  return locale === "gu-IN" ? 0 : locale === "hi-IN" ? 1 : null;
}

const months: Record<string, [string, string]> = {
  Jan: ["જાન્યુ", "जन"], Feb: ["ફેબ્રુ", "फ़र"], Mar: ["માર્ચ", "मार्च"], Apr: ["એપ્રિ", "अप्रै"], May: ["મે", "मई"], Jun: ["જૂન", "जून"],
  Jul: ["જુલા", "जुला"], Aug: ["ઑગ", "अग"], Sep: ["સપ્ટે", "सित"], Sept: ["સપ્ટે", "सित"], Oct: ["ઑક્ટો", "अक्टू"], Nov: ["નવે", "नव"], Dec: ["ડિસે", "दिस"]
};
export function translateMonths(text: string, column: 0 | 1) {
  return text.replace(/\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sept|Sep|Oct|Nov|Dec)\b/g, (m) => months[m][column]);
}

