function database({role='Admin',selectedCompany=company,inserted=[]}={}){
 const calls=[],transactions=[];
 return {calls,transactions,database:{scoped:async(scope,operation)=>{
  const tx={companyId:scope.companyId,actorId:actor,sessionId:session,permission:scope.permission,query:async(sql,values)=>{
   calls.push({sql,values,tx});if(sql.includes('saas.company_context'))return {rows:[{role}]};
   if(sql.includes('saas.company_selections'))return {rows:selectedCompany?[{company_id:selectedCompany}]:[]};
   if(sql.includes('invoice_routing.initialize_module_reviews'))return {rows:inserted.map(document_id=>({document_id}))};
   if(sql.includes('saas.audit_events'))return {rows:[],rowCount:1};
   throw new Error(`Unexpected query: ${sql}`);
  }};transactions.push(tx);return operation(tx);
 }}};
}
