test('initializer returns only inserted IDs and audits each new review in the same company transaction',async()=>{
 const ids=['ae5f2665-ff43-4cb4-83fc-f312fe292d96','be5f2665-ff43-4cb4-83fc-f312fe292d96'],mock=database({inserted:ids});
 const scope={companyId:company,sessionCookie:'opaque',permission:'invoices:write'};
 const result=await reviews.moduleReviewService(mock.database).initialize(scope,'vat');
 assert.deepEqual(result,{companyId:company,module:'vat',insertedCount:2,documentIds:ids});
 const init=mock.calls.find(call=>call.sql.includes('initialize_module_reviews'));
 const audits=mock.calls.filter(call=>call.sql.includes('saas.audit_events'));
 assert.deepEqual(init.values,[company,'vat']);assert.equal(audits.length,2);
 assert.deepEqual(audits.map(call=>call.values.slice(0,4)),ids.map(id=>[company,actor,'document.vat-review-initialized',id]));
 assert.ok(audits.every(audit=>init.tx===audit.tx));assert.equal(mock.transactions.length,1);
 const repeat=database({inserted:[]});
 const noOp=await reviews.moduleReviewService(repeat.database).initialize(scope,'vat');
 assert.deepEqual(noOp,{companyId:company,module:'vat',insertedCount:0,documentIds:[]});
 assert.equal(repeat.calls.filter(call=>call.sql.includes('initialize_module_reviews')).length,1);
 assert.equal(repeat.calls.filter(call=>call.sql.includes('saas.audit_events')).length,0);
});
